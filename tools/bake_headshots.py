#!/usr/bin/env python3
"""Pre-bake pixel-art headshots from nflverse so the dex works offline.

Downloads every player's nflverse headshot, converts it into a small
limited-palette pixel portrait and writes js/headshots.js, which maps
Madden player id -> PNG data URI. index.html loads it automatically if
present; without it the browser pixelates headshots live instead.

Usage:
    python3 tools/bake_headshots.py                 # all players
    python3 tools/bake_headshots.py --team BUF      # just one team
    python3 tools/bake_headshots.py --size 64 --colors 40

Requires: Pillow   (pip install pillow)
"""
import argparse
import base64
import io
import json
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image, ImageEnhance

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / "data/headshot_cache"


def load_data():
    txt = (ROOT / "js/data.js").read_text(encoding="utf-8")
    return json.loads(txt[txt.index("{"): txt.rindex("}") + 1])


def fetch(url, dest):
    if dest.exists():
        return dest.read_bytes()
    req = urllib.request.Request(url, headers={"User-Agent": "gridiron-dex/1.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        data = r.read()
    dest.write_bytes(data)
    return data


def pixelate(raw, size=64, colors=40, outline=(16, 16, 24, 255)):
    """Photo -> 16-bit style portrait: crop to the face, downscale, boost, reduce palette, outline."""
    im = Image.open(io.BytesIO(raw)).convert("RGBA")
    w, h = im.size
    # NFL headshots are head-and-shoulders; keep a square biased to the top.
    side = min(w, h)
    left = (w - side) // 2
    top = int((h - side) * 0.15)
    im = im.crop((left, top, left + side, top + side))
    im = im.resize((size, size), Image.LANCZOS)

    alpha = im.getchannel("A").point(lambda a: 255 if a >= 128 else 0)
    rgb = Image.new("RGB", im.size, (0, 0, 0))
    rgb.paste(im, mask=alpha)
    rgb = ImageEnhance.Color(rgb).enhance(1.2)
    rgb = ImageEnhance.Contrast(rgb).enhance(1.08)
    q = rgb.quantize(colors=colors, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    out = q.convert("RGBA")
    out.putalpha(alpha)

    # 1px dark outline around the opaque silhouette (only if the source had transparency)
    px = out.load()
    a = alpha.load()
    if any(a[x, y] == 0 for x in range(size) for y in (0, size - 1)):
        for y in range(size):
            for x in range(size):
                if a[x, y]:
                    continue
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < size and 0 <= ny < size and a[nx, ny]:
                        px[x, y] = outline
                        break
    buf = io.BytesIO()
    out.save(buf, "PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", type=int, default=64)
    ap.add_argument("--colors", type=int, default=40)
    ap.add_argument("--team", help="only bake one team (abbr, e.g. BUF)")
    ap.add_argument("--workers", type=int, default=8)
    args = ap.parse_args()

    data = load_data()
    players = [p for p in data["players"] if p.get("headshot")]
    if args.team:
        players = [p for p in players if p["team"] == args.team.upper()]
    CACHE.mkdir(parents=True, exist_ok=True)

    out_path = ROOT / "js/headshots.js"
    baked = {}
    if out_path.exists():
        txt = out_path.read_text()
        baked = json.loads(txt[txt.index("{"): txt.rindex("}") + 1])

    def work(p):
        try:
            raw = fetch(p["headshot"], CACHE / f'{p["id"]}.img')
            return p["id"], pixelate(raw, args.size, args.colors)
        except Exception as e:  # noqa: BLE001
            print(f'  ! {p["first"]} {p["last"]}: {e}', file=sys.stderr)
            return p["id"], None

    with ThreadPoolExecutor(args.workers) as ex:
        for i, (pid, uri) in enumerate(ex.map(work, players), 1):
            if uri:
                baked[str(pid)] = uri
            if i % 100 == 0:
                print(f"{i}/{len(players)}", file=sys.stderr)

    out_path.write_text("// Generated by tools/bake_headshots.py\nwindow.DEX_HEADSHOTS = " +
                        json.dumps(baked, separators=(",", ":")) + ";\n")
    print(f"baked {len(baked)} headshots -> {out_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
